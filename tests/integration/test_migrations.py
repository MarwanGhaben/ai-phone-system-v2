def docker_call(executable, arguments, timeout=20):
    env = {k: v for k, v in os.environ.items() if not k.startswith("DOCKER_")}
    return subprocess.run(
        [executable, "--context", "desktop-linux", *arguments],
        env=env, capture_output=True, text=True, timeout=timeout, check=False,
    )


def docker_ok(executable, arguments, timeout=20):
    result = docker_call(executable, arguments, timeout)
    if result.returncode:
        raise RuntimeError("T005 local Docker prerequisite/command failed")
    return result.stdout


def cleanup(executable, candidates):
    """Visit every exact candidate even after an uncertain create/remove result."""
    errors = []
    for name in reversed(candidates):
        try:
            docker_call(executable, ["container", "rm", "--force", "--volumes", name])
            result = docker_call(executable, ["container", "inspect", name])
            if result.returncode and "no such" in result.stderr.lower():
                continue
        except (OSError, subprocess.TimeoutExpired):
            pass
        errors.append(name)
    return errors


def auth_password_statements():
    """Read both real UPDATE paths without importing live-client modules."""
    tree = ast.parse((ROOT / "services/dashboard/auth_service.py").read_text("utf-8"))
    return [
        node.value for node in ast.walk(tree)
        if isinstance(node, ast.Constant) and isinstance(node.value, str)
        and node.value.startswith("UPDATE admin_users SET password_hash")
    ]


class OfflineTests(unittest.TestCase):
    def setUp(self):
        self.runner = importlib.import_module("migrations.runner")

    def invoke(self, args):
        output = io.StringIO()
        with contextlib.redirect_stdout(output), contextlib.redirect_stderr(output):
            code = self.runner.main(args)
        return code, output.getvalue()

    def test_bootstrap_schema_is_explicit_plain_sql(self):
        sql = BOOTSTRAP_SCHEMA_PATH.read_text(encoding="utf-8")
        upper = sql.upper()
        self.assertNotIn("\\ECHO", upper)
        self.assertNotIn("IF NOT EXISTS", upper)
        self.assertNotIn("CREATE OR REPLACE", upper)
        self.assertNotIn("SCHEMA_MIGRATIONS", upper)
        self.assertNotRegex(upper, r"\b(BEGIN|COMMIT|ROLLBACK)\s*;")
        self.assertNotRegex(upper, r"\bCREATE\s+(EXTENSION|SCHEMA)\b")
        self.assertNotRegex(upper, r"\bINSERT\s+INTO\b")
        self.assertNotRegex(upper, r"\bSETVAL\s*\(")
        self.assertNotRegex(upper, r"\bSELECT\s+[^;]*\bNEXTVAL\s*\(")
        self.assertNotRegex(upper, r"\bREFERENCES\s+(?!PUBLIC\.)")
        self.assertNotRegex(
            upper,
            r"(?m)^CREATE\s+(?:TABLE|SEQUENCE|FUNCTION)\s+(?!PUBLIC\.)",
        )
        self.assertEqual(
            set(re.findall(r"(?im)^CREATE TABLE public\.([a-z_]+)\s*\(", sql)),
            set(APPLICATION_TABLE_COLUMNS),
        )
        self.assertEqual(len(re.findall(r"(?im)^CREATE SEQUENCE public\.", sql)), 9)
        self.assertEqual(len(re.findall(r"(?im)^CREATE INDEX ", sql)), 26)
        self.assertEqual(
            len(re.findall(r"(?im)^\s*BEFORE UPDATE ON public\.", sql)),
            7,
        )

    def test_missing_configuration_never_uses_application_url(self):
        with mock.patch.dict(os.environ, {"DATABASE_URL": SENTINEL}, clear=True), \
                mock.patch.object(self.runner, "_connect", new_callable=mock.AsyncMock) as connect:
            code, output = self.invoke(["--apply"])
        self.assertNotEqual(code, 0)
        self.assertIn("configuration", output)
        self.assertNotIn(SENTINEL, output)
        connect.assert_not_called()

    def test_cli_requires_exactly_one_mode_and_redacts_bad_arguments(self):
        for args in (
            [], ["--apply", "--status"], ["--apply", "--prepare"],
            ["--status", "--prepare"], ["--sql", SENTINEL], [SENTINEL],
        ):
            with self.subTest(args=args):
                code, output = self.invoke(args)
                self.assertNotEqual(code, 0)
                self.assertNotIn(SENTINEL, output)
                self.assertNotIn("Traceback", output)
        with self.assertRaisesRegex(self.runner.MigrationError, "choose exactly one"):
            asyncio.run(self.runner.run(apply=True, prepare=True))

    def test_connection_failure_redacts_driver_details(self):
        with mock.patch.dict(os.environ, {"MIGRATION_DATABASE_URL": SENTINEL}), \
                mock.patch.object(self.runner, "_connect", new_callable=mock.AsyncMock,
                                  side_effect=RuntimeError(SENTINEL)):
            code, output = self.invoke(["--status"])
        self.assertNotEqual(code, 0)
        self.assertIn("connection", output)
        self.assertNotIn(SENTINEL, output)
        self.assertNotIn("Traceback", output)

    def test_driver_connect_is_bounded_and_does_not_import_application(self):
        connect = mock.AsyncMock(return_value=object())
        with mock.patch.dict(sys.modules, {"asyncpg": types.SimpleNamespace(connect=connect)}):
            asyncio.run(self.runner._connect("postgresql://synthetic:invented@127.0.0.1:5432/t005"))
        self.assertGreater(connect.call_args.kwargs["timeout"], 0)
        self.assertLessEqual(connect.call_args.kwargs["timeout"], 15)
        self.assertLessEqual(connect.call_args.kwargs["command_timeout"], 30)
        # The runner itself must not import application modules (the full suite may).
        tree = ast.parse((ROOT / "migrations/runner.py").read_text("utf-8"))
        modules = [node.module for node in ast.walk(tree) if isinstance(node, ast.ImportFrom)]
        self.assertFalse(any(m and m.startswith(("config", "services")) for m in modules))

    def test_incomplete_url_never_inherits_database_or_credentials(self):
        connect = mock.AsyncMock()
        with mock.patch.dict(sys.modules, {"asyncpg": types.SimpleNamespace(connect=connect)}), \
                mock.patch.dict(os.environ, {"PGHOST": SENTINEL, "PGPASSWORD": SENTINEL,
                                            "PGDATABASE": SENTINEL}):
            for url in ("postgresql:///", "postgresql://user@localhost/test",
                        "postgresql://user:password@localhost", "invalid"):
                with self.subTest(url=url):
                    with self.assertRaisesRegex(self.runner.MigrationError, "configuration"):
                        asyncio.run(self.runner._connect(url))
        connect.assert_not_called()

    def test_exact_byte_manifest_and_auth_path_oracle(self):
        revision, = self.runner.MANIFEST
        self.assertEqual(revision, ("0001", "0001_admin_users_updated_at.sql"))
        sql, checksum = self.runner._load_revision()
        raw = (ROOT / "migrations" / revision[1]).read_bytes()
        self.assertEqual(checksum, hashlib.sha256(raw).hexdigest())
        self.assertEqual(sql, raw.decode("utf-8"))
        self.assertEqual(auth_password_statements(), [
            "UPDATE admin_users SET password_hash = $1, updated_at = NOW() WHERE id = $2"
        ] * 2)

    def test_prepare_assets_have_pinned_exact_byte_checksums(self):
        contract = importlib.import_module("migrations.schema_contract")
        _, revision_checksum = self.runner._load_revision()
        bootstrap_sql, bootstrap_checksum = self.runner._load_bootstrap()
        self.assertEqual(revision_checksum, contract.REVISION_CHECKSUM)
        self.assertEqual(bootstrap_checksum, contract.BOOTSTRAP_CHECKSUM)
        self.assertEqual(
            bootstrap_sql,
            (ROOT / "migrations/bootstrap_schema.sql").read_bytes().decode("utf-8"),
        )
        self.assertIn(
            "migrations/*.sql text eol=lf",
            (ROOT / ".gitattributes").read_text(encoding="utf-8").splitlines(),
        )

    def test_connection_closed_after_transaction_failure(self):
        conn = mock.Mock()
        conn.close = mock.AsyncMock()
        conn.transaction.side_effect = RuntimeError(SENTINEL)
        with mock.patch.dict(os.environ, {"MIGRATION_DATABASE_URL": SENTINEL}), \
                mock.patch.object(self.runner, "_connect", new_callable=mock.AsyncMock,
                                  return_value=conn):
            code, output = self.invoke(["--apply"])
        self.assertNotEqual(code, 0)
        self.assertNotIn(SENTINEL, output)
        conn.close.assert_awaited_once()

    def test_failed_close_terminates_connection_without_leaking_error(self):
        conn = mock.Mock()
        conn.close = mock.AsyncMock(side_effect=RuntimeError(SENTINEL))
        conn.transaction.side_effect = RuntimeError(SENTINEL)
        with mock.patch.dict(os.environ, {"MIGRATION_DATABASE_URL": SENTINEL}), \
                mock.patch.object(self.runner, "_connect", new_callable=mock.AsyncMock,
                                  return_value=conn):
            code, output = self.invoke(["--apply"])
        self.assertNotEqual(code, 0)
        self.assertNotIn(SENTINEL, output)
        conn.terminate.assert_called_once()

    def test_cleanup_continues_and_reports_exact_uncertain_resource(self):
        def fake(executable, arguments, timeout=20):
            if arguments[-1] == "t005-uncertain":
                raise subprocess.TimeoutExpired("docker", 20)
            return subprocess.CompletedProcess([], 1, "", "No such container")
        with mock.patch(__name__ + ".docker_call", side_effect=fake) as call:
            self.assertEqual(cleanup("docker", ["t005-absent", "t005-uncertain"]),
                             ["t005-uncertain"])
        self.assertEqual(call.call_count, 3)

    def test_docker_always_uses_explicit_context_and_strips_overrides(self):
        with mock.patch.dict(os.environ, {"DOCKER_HOST": SENTINEL}), \
                mock.patch("subprocess.run") as run:
            docker_call("docker", ["info"])
        self.assertEqual(run.call_args.args[0],
                         ["docker", "--context", "desktop-linux", "info"])
        self.assertNotIn("DOCKER_HOST", run.call_args.kwargs["env"])


