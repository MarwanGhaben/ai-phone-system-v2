def docker_call(executable, arguments, timeout=20):
    env = {k: v for k, v in os.environ.items() if not k.startswith("DOCKER_")}
    return subprocess.run(
        [executable, "--context", "desktop-linux", *arguments],
        env=env, capture_output=True, text=True, timeout=timeout, check=False,
    )


def docker_ok(executable, arguments, timeout=20):
    result = docker_call(executable, arguments, timeout)
    if result.returncode:
        raise RuntimeError("T005 local Docker prerequisite/command failed")
    return result.stdout


def cleanup(executable, candidates):
    """Visit every exact candidate even after an uncertain create/remove result."""
    errors = []
    for name in reversed(candidates):
        try:
            docker_call(executable, ["container", "rm", "--force", "--volumes", name])
            result = docker_call(executable, ["container", "inspect", name])
            if result.returncode and "no such" in result.stderr.lower():
                continue
        except (OSError, subprocess.TimeoutExpired):
            pass
        errors.append(name)
    return errors


