class PostgreSQLTests(unittest.IsolatedAsyncioTestCase):
    @classmethod
    def setUpClass(cls):
        cls.driver = importlib.import_module("asyncpg")
        cls.runner = importlib.import_module("migrations.runner")
        cls.docker = shutil.which("docker")
        if cls.docker is None and DOCKER_FALLBACK.is_file():
            cls.docker = str(DOCKER_FALLBACK)
        if cls.docker is None:
            raise RuntimeError("T005 requires existing local Docker; no installation attempted")
        details = json.loads(docker_ok(cls.docker, ["context", "inspect", "desktop-linux"]))
        endpoint = details[0]["Endpoints"]["docker"]["Host"]
        if not (endpoint.startswith("npipe:////./pipe/") or endpoint.startswith("unix:///")):
            raise RuntimeError("T005 desktop-linux endpoint is not a local socket")
        if docker_ok(cls.docker, ["info", "--format", "{{.OSType}}"]).strip() != "linux":
            raise RuntimeError("T005 requires local Linux Docker")
        listing = docker_ok(cls.docker, ["image", "ls", "--format", "{{json .}}"])
        candidates = [json.loads(line) for line in listing.splitlines() if line]
        images = sorted({row["Repository"] + ":" + row["Tag"] for row in candidates
                         if row["Repository"] in ("postgres", "docker.io/library/postgres")
                         and re.fullmatch(r"16(?:\.\d+)?(?:-[a-z0-9.-]+)?", row["Tag"])})
        if not images:
            raise RuntimeError("T005 requires an existing official PostgreSQL 16 image; no pull")
        image = json.loads(docker_ok(cls.docker, ["image", "inspect", images[0]]))[0]
        if "PG_MAJOR=16" not in image["Config"]["Env"]:
            raise RuntimeError("T005 local image does not declare PostgreSQL 16")
        cls.name = "t005-migrations-" + uuid.uuid4().hex
        cls.database = "t005_" + uuid.uuid4().hex
        cls.candidates = []
        try:
            cls.candidates.append(cls.name)  # Track before uncertain dispatch.
            docker_ok(cls.docker, [
                "create", "--pull", "never", "--name", cls.name,
                "--memory", "192m", "--memory-swap", "192m", "--cpus", "0.5",
                "--pids-limit", "128", "--shm-size", "32m", "--network", "bridge",
                "--publish", "127.0.0.1::5432",
                "--tmpfs", "/var/lib/postgresql/data:rw,noexec,nosuid,size=128m",
                "--env", "PGDATA=/var/lib/postgresql/data/pgdata",
                "--env", "POSTGRES_USER=t005", "--env", "POSTGRES_PASSWORD=t005-synthetic",
                "--env", "POSTGRES_DB=" + cls.database, image["Id"],
                "-c", "shared_buffers=16MB", "-c", "max_connections=12",
                "-c", "work_mem=1MB", "-c", "maintenance_work_mem=16MB",
            ], timeout=30)
            docker_ok(cls.docker, ["start", cls.name], timeout=30)
            ports = json.loads(docker_ok(cls.docker, [
                "inspect", "--format", "{{json .NetworkSettings.Ports}}", cls.name]))
            binding, = ports["5432/tcp"]
            if binding["HostIp"] != "127.0.0.1":
                raise RuntimeError("T005 port is not loopback-only")
            cls.dsn = ("postgresql://t005:t005-synthetic@127.0.0.1:"
                       + str(int(binding["HostPort"])) + "/" + cls.database)
            deadline = time.monotonic() + 45
            while time.monotonic() < deadline:
                result = docker_call(cls.docker, ["exec", cls.name, "pg_isready",
                                                 "-h", "127.0.0.1", "-U", "t005", "-d", cls.database], 5)
                if result.returncode == 0:
                    break
                time.sleep(0.25)
            else:
                raise RuntimeError("T005 isolated PostgreSQL startup timed out")
        except BaseException:
            errors = cleanup(cls.docker, cls.candidates)
            if errors:
                warnings.warn("T005 cleanup unconfirmed: " + ", ".join(errors), RuntimeWarning)
            raise

    @classmethod
    def tearDownClass(cls):
        errors = cleanup(cls.docker, cls.candidates)
        if errors:
            raise AssertionError("T005 cleanup unconfirmed: " + ", ".join(errors))
        print("T005 cleanup confirmed: " + cls.name)

