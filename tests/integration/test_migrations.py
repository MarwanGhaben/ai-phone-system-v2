    def test_bootstrap_schema_is_explicit_plain_sql(self):
        sql = BOOTSTRAP_SCHEMA_PATH.read_text(encoding="utf-8")
        upper = sql.upper()
        self.assertNotIn("\\ECHO", upper)
        self.assertNotIn("IF NOT EXISTS", upper)
        self.assertNotIn("CREATE OR REPLACE", upper)
        self.assertNotIn("SCHEMA_MIGRATIONS", upper)
        self.assertNotRegex(upper, r"\b(BEGIN|COMMIT|ROLLBACK)\s*;")
